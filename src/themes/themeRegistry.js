export function getTheme(themeId) {
  return THEMES.find((theme) => theme.id === themeId) || THEMES[0]
}

export function resolveTheme(theme, settings = {}) {
  const fontFamily = settings.fontFamily || theme.fontFamily
  return {
    ...theme,
    fontFamily,
    accent: settings.accentColor || theme.accent,
    background: settings.useCustomBackground && settings.backgroundColor
      ? [settings.backgroundColor, settings.backgroundColor]
      : theme.background,
    ...(settings.backgroundImage ? {
      text: '#FFFFFF',
      muted: '#F1F1F1',
      divider: 'rgba(255,255,255,0.3)',
    } : {}),
    layout: settings.layout || theme.layout,
    dividerStyle: settings.dividerStyle || theme.dividerStyle,
  }
}

export function getThemeThumbnailStops(theme) {
  return theme.background
}
